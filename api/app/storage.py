"""File storage for uploaded protocols.

Two interchangeable backends behind one tiny interface (save / read / delete):

  LocalStorage  a folder, e.g. a Docker volume shared by the API and the worker
  S3Storage     an S3 bucket, encrypted at rest. On AWS (EKS) the pod gets
                credentials from its IAM role (IRSA), so no keys are stored anywhere.

Pick with STORAGE_BACKEND=local|s3. Nothing else in the app knows which one is used.
"""

import uuid
from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol

import anyio
import boto3
from botocore.config import Config
from botocore.exceptions import ClientError

from app.config import settings


class Storage(Protocol):
    async def save(self, data: bytes, suffix: str) -> str: ...
    async def read(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...


def _new_name(suffix: str) -> str:
    # Never use the user's filename in the storage key.
    return f"{uuid.uuid4().hex}{suffix}"


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        # Keys are generated by us, but never trust a path blindly.
        path = (self.root / key).resolve()
        if self.root.resolve() not in path.parents:
            raise ValueError("Invalid storage key")
        return path

    async def save(self, data: bytes, suffix: str) -> str:
        key = f"protocols/{_new_name(suffix)}"
        path = self._path(key)
        await anyio.Path(path.parent).mkdir(parents=True, exist_ok=True)
        await anyio.Path(path).write_bytes(data)
        return key

    async def read(self, key: str) -> bytes:
        return await anyio.Path(self._path(key)).read_bytes()

    async def delete(self, key: str) -> None:
        await anyio.Path(self._path(key)).unlink(missing_ok=True)


class S3Storage:
    """boto3 is synchronous, so each call runs in a worker thread (never blocks the event loop)."""

    def __init__(self, bucket: str, prefix: str = "protocols/", client: Any | None = None) -> None:
        self.bucket = bucket
        self.prefix = prefix
        self.client = client or boto3.client(
            "s3",
            region_name=settings.aws_region,
            endpoint_url=settings.s3_endpoint_url,
            config=Config(retries={"mode": "standard", "max_attempts": 5}),
        )

    def _check(self, key: str) -> str:
        if not key.startswith(self.prefix) or ".." in key:
            raise ValueError("Invalid storage key")
        return key

    async def save(self, data: bytes, suffix: str) -> str:
        key = f"{self.prefix}{_new_name(suffix)}"
        await anyio.to_thread.run_sync(
            lambda: self.client.put_object(
                Bucket=self.bucket,
                Key=key,
                Body=data,
                ServerSideEncryption="AES256",
                ContentType="application/pdf" if suffix == ".pdf" else "text/plain",
            )
        )
        return key

    async def read(self, key: str) -> bytes:
        key = self._check(key)

        def _get() -> bytes:
            return self.client.get_object(Bucket=self.bucket, Key=key)["Body"].read()

        return await anyio.to_thread.run_sync(_get)

    async def delete(self, key: str) -> None:
        key = self._check(key)
        try:
            await anyio.to_thread.run_sync(
                lambda: self.client.delete_object(Bucket=self.bucket, Key=key)
            )
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") not in ("NoSuchKey", "404"):
                raise


@lru_cache
def _s3_storage() -> S3Storage:
    if not settings.s3_bucket:
        raise RuntimeError("STORAGE_BACKEND=s3 needs S3_BUCKET")
    return S3Storage(settings.s3_bucket, settings.s3_prefix)


def get_storage() -> Storage:
    if settings.storage_backend == "s3":
        return _s3_storage()
    return LocalStorage(settings.upload_dir)
