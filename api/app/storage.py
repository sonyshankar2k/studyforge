"""File storage for uploaded protocols.

LocalStorage writes to a folder (a Docker volume shared by the API and the worker).
The interface is deliberately tiny so Week 4 can add an S3Storage with the same
three methods and nothing else has to change.
"""

import uuid
from pathlib import Path
from typing import Protocol

import anyio

from app.config import settings


class Storage(Protocol):
    async def save(self, data: bytes, suffix: str) -> str: ...
    async def read(self, key: str) -> bytes: ...
    async def delete(self, key: str) -> None: ...


class LocalStorage:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        # Keys are generated by us (uuid + suffix), but never trust a path blindly.
        path = (self.root / key).resolve()
        if self.root.resolve() not in path.parents:
            raise ValueError("Invalid storage key")
        return path

    async def save(self, data: bytes, suffix: str) -> str:
        key = f"protocols/{uuid.uuid4().hex}{suffix}"
        path = self._path(key)
        await anyio.Path(path.parent).mkdir(parents=True, exist_ok=True)
        await anyio.Path(path).write_bytes(data)
        return key

    async def read(self, key: str) -> bytes:
        return await anyio.Path(self._path(key)).read_bytes()

    async def delete(self, key: str) -> None:
        await anyio.Path(self._path(key)).unlink(missing_ok=True)


def get_storage() -> Storage:
    return LocalStorage(settings.upload_dir)
